import type { GroupLock } from "../forget.js";
import type { RegenerateOutcome } from "./regenerate.js";
import type { HighlightStore } from "./store.js";

export type SchedulerOptions = {
  store: Pick<HighlightStore, "staleDue" | "nightlyDue" | "claimOnDemand">;
  /** The per-group lock shared with capture and forget. */
  lock: GroupLock;
  regenerate: (groupId: string) => Promise<RegenerateOutcome>;
  logger: { info: (m: string) => void; warn: (m: string) => void };
  now: () => Date;
  /** Expired recall rows, swept each tick (writes also sweep; this covers quiet periods). */
  sweep?: () => Promise<unknown>;
  intervalMs?: number;
  debounceSec?: number;
  dailyCap?: number;
  nightlyHourUtc?: number;
  /** Most groups one tick regenerates per pass. */
  batch?: number;
};

export type HighlightScheduler = {
  start(): void;
  stop(): Promise<void>;
  /** One pass now (the timer calls this). Never throws. */
  tick(): Promise<void>;
  /**
   * A read with no highlights: take an on-demand slot (creating the placeholder
   * row) and regenerate now. True when a generation is pending (including one
   * already in flight here); false when today's cap is used or stopped.
   */
  requestNow(groupId: string): Promise<boolean>;
};

/**
 * Freshness worker (A&D §4.4): every minute, regenerate groups stale for at least
 * the debounce and under today's on-demand cap; in the nightly hour (03:00 UTC),
 * once per day, every stale group whatever its count. Runs are serial and take
 * the per-group lock. Logs counts only.
 */
export function createHighlightScheduler(opts: SchedulerOptions): HighlightScheduler {
  const intervalMs = opts.intervalMs ?? 60_000;
  const debounceSec = opts.debounceSec ?? 120;
  const cap = opts.dailyCap ?? 3;
  const nightlyHour = opts.nightlyHourUtc ?? 3;
  const batch = opts.batch ?? 50;
  let timer: ReturnType<typeof setInterval> | undefined;
  let running: Promise<void> | null = null;
  let stopped = false;
  // Nightly progress for the current UTC day: groups already regenerated by the
  // nightly pass. The pass works through stale groups `batch` per tick for the whole
  // nightly hour, so a large night never starves the minute pass.
  let nightlyDay: string | null = null;
  const nightlyDone = new Set<string>();
  // Groups queued or regenerating in THIS process: a repeat request is "pending",
  // not another slot and another model call.
  const inflight = new Set<string>();
  const background = new Set<Promise<unknown>>();

  const run = async (groupId: string): Promise<boolean> => {
    inflight.add(groupId);
    try {
      await opts.lock([groupId], () => opts.regenerate(groupId));
      return true;
    } catch {
      opts.logger.warn("memory-highlights: a regeneration failed");
      return false;
    } finally {
      inflight.delete(groupId);
    }
  };

  const pass = async () => {
    let regenerated = 0;
    const now = opts.now();
    const day = now.toISOString().slice(0, 10);
    try {
      if (now.getUTCHours() === nightlyHour) {
        if (nightlyDay !== day) {
          nightlyDay = day;
          nightlyDone.clear();
        }
        const due = (await opts.store.nightlyDue(batch + nightlyDone.size)).filter(
          (g) => !nightlyDone.has(g) && !inflight.has(g),
        );
        for (const g of due.slice(0, batch)) {
          nightlyDone.add(g);
          regenerated += (await run(g)) ? 1 : 0;
        }
      }
    } catch {
      opts.logger.warn("memory-highlights: nightly pass failed");
    }
    try {
      for (const g of await opts.store.staleDue({ debounceSec, cap, limit: batch })) {
        // Update-only claim: the worker never creates a row (a forget may have
        // deleted it since staleDue listed it).
        if (!inflight.has(g) && (await opts.store.claimOnDemand(g, cap))) {
          regenerated += (await run(g)) ? 1 : 0;
        }
      }
    } catch {
      opts.logger.warn("memory-highlights: scheduler pass failed");
    }
    if (opts.sweep) {
      try {
        await opts.sweep();
      } catch {
        opts.logger.warn("memory-highlights: recall sweep failed");
      }
    }
    if (regenerated > 0) {
      opts.logger.info(`memory-highlights: regenerated groups=${regenerated}`);
    }
  };

  const tick = async () => {
    if (running || stopped) {
      return;
    }
    running = pass().finally(() => {
      running = null;
    });
    await running;
  };

  return {
    start() {
      if (timer || stopped) {
        return;
      }
      timer = setInterval(() => void tick(), intervalMs);
      timer.unref?.();
    },
    async stop() {
      stopped = true;
      if (timer) {
        clearInterval(timer);
        timer = undefined;
      }
      await running;
      await Promise.allSettled([...background]);
    },
    tick,
    async requestNow(groupId) {
      if (stopped) {
        return false;
      }
      if (inflight.has(groupId)) {
        return true; // already pending here: no second slot, no second model call
      }
      if (!(await opts.store.claimOnDemand(groupId, cap, { create: true }))) {
        return false;
      }
      const p = run(groupId).finally(() => background.delete(p));
      background.add(p);
      return true;
    },
  };
}
