// ---------------------------------------------------------------------------
// Assembly — TOOL_DEFS is DERIVED, not declared.
//
// No runtime empty-roster guard, deliberately (QG2-14): an empty roster makes
// `RosterToolName = never`, which fails the `NOT_YET_IMPLEMENTED` satisfies
// clause and every `TOOL_LOCALS` key at COMPILE time — a runtime throw here
// is unreachable in any typechecked build, and at module top level it would
// crash extension load rather than degrade. The generator additionally
// refuses to emit an empty roster.
// ---------------------------------------------------------------------------

/** Roster entries whose names are implemented (i.e. not deferred). */
type ImplementedEntry = Extract<(typeof TOOL_ROSTER)[number], { name: ImplementedName }>;

const PENDING = new Set<string>(NOT_YET_IMPLEMENTED);

/**
 * The assembled tool surface: roster (name, mcpToolName, description) joined
 * with locals (label, parameters). Exported so tests can pin the derivation.
 */
export const TOOL_DEFS: readonly ToolDef[] = TOOL_ROSTER.filter(
  (t): t is ImplementedEntry => !PENDING.has(t.name),
).map((t) => ({
  name: t.name,
  label: TOOL_LOCALS[t.name].label,
  description: t.description,
  parameters: TOOL_LOCALS[t.name].parameters,
  mcpToolName: t.mcpToolName,
}));

// ---------------------------------------------------------------------------
// Factory — creates tools bound to a specific user's auth token
// ---------------------------------------------------------------------------

export function createAllTools(
  baseUrl: string,
  authToken: string,
  // Optional Braintrust tracer (PHI-safe). When omitted (the default-OFF
  // path), tool execution calls the MCP transport directly — byte-identical
  // behavior, no braintrust code loaded.
  tracer?: Tracer,
): Array<{
  name: string;
  label: string;
  description: string;
  parameters: TObject;
  execute: (toolCallId: string, args: unknown) => Promise<AgentToolResult<unknown>>;
}> {
  return TOOL_DEFS.map((def) => ({
    name: def.name,
    label: def.label,
    description: def.description,
    parameters: def.parameters,
    async execute(_toolCallId: string, args: unknown): Promise<AgentToolResult<unknown>> {
      const params = (args ?? {}) as Record<string, unknown>;
      const call = () => callSyntropyTool(baseUrl, authToken, def.mcpToolName, params);
      const result = tracer
        ? await tracer.traceMcp("Syntropy", def.mcpToolName, params, call)
        : await call();
      return toAgentResult(result);
    },
  }));
}
