/** A fully assembled tool definition: roster fields + local fields. */
interface ToolDef {
  readonly name: string;
  readonly label: string;
  readonly description: string;
  readonly parameters: TObject;
  readonly mcpToolName: string;
}

/**
 * Rostered tools this file deliberately does NOT implement yet.
 *
 * #200 fixes the CONTRACT MECHANISM; it does not expand the agent's tool
 * surface (CTO ruling: no new tool rides this ticket). `syntropy_my_protocols`
 * is live and non-deprecated upstream but has never been exposed here, and
 * wiring it needs `parameters` authored against its input contract — real
 * work with a user-visible 4xx failure mode if guessed.
 *
 * Listing a name here is load-bearing, and DEFERRING IS NOT FREE: moving a
 * tool from implemented to deferred requires (1) deleting its `TOOL_LOCALS`
 * entry (the Record type forces it) and (2) editing the pinned expectation in
 * `tools.test.ts` (which asserts this list's exact contents). Shrinking the
 * agent surface is a two-file conscious act, never a silent side effect.
 *
 * When the SJ submodule pin advances and brings a NEW manifest tool, the
 * Record below breaks the build (TS2739) until the tool is implemented or
 * consciously added here. Silence is not an option in either direction.
 */
export const NOT_YET_IMPLEMENTED = [
  "syntropy_my_protocols",
] as const satisfies readonly RosterToolName[];

type PendingName = (typeof NOT_YET_IMPLEMENTED)[number];

/** Every rostered tool this file must supply locals for. */
type ImplementedName = Exclude<RosterToolName, PendingName>;

/** What the manifest does NOT carry (yet) — supplied locally per tool. */
interface ToolLocal {
  readonly label: string;
  readonly parameters: TObject;
}

