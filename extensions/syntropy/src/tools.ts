/**
 * Syntropy Health tool definitions for the OpenClaw agent.
 *
 * Each tool wraps a Syntropy MCP tool, calling it via HTTP with the
 * user's stored API token (standard Bearer auth).
 *
 * ──────────────────────────────────────────────────────────────────────────
 * Schema source of truth (#200)
 * ──────────────────────────────────────────────────────────────────────────
 * The architecture of record is F.1 = (c) Layered
 * (docs/superpowers/plans/2026-05-11-sj-mcp-center-layered.md): ONE schema
 * source of truth, every surface regenerated from it. For this file that
 * source is the SJ tool manifests, reaching here as the GENERATED roster
 * (`./generated/tool-roster.generated.ts`, regenerated by
 * `npm run codegen:openclaw-tool-roster` in the monorepo's `shared/schemas/`
 * from the PINNED Syntropy-Journals submodule commit).
 *
 * What is roster-derived vs local:
 *
 *   ROSTER-DERIVED (generated, verbatim from the manifest):
 *     - membership (which tools exist)
 *     - `mcpToolName` (the SJ-side wire name to call)
 *     - `description` (what the agent reads to pick a tool)
 *
 *   LOCAL (this file, because the manifest does not carry them yet):
 *     - `label` (a UI string that exists nowhere upstream)
 *     - `parameters` (TypeBox schemas; the manifest names an
 *       `input_model_class` but those Pydantic input models are not exported
 *       into `shared/schemas/syntropy.schema.json` — zero `*Input` defs).
 *       Exporting them upstream is the follow-up that completes F.1 here.
 *
 *   UPSTREAM BUT NOT PROPAGATED (known gap, tracked in the roster-derivation
 *   follow-up issue): the manifests also carry `prompt_hints.when_to_call` /
 *   `do_not_call` (negative routing guidance) and `available_channels` (SJ's
 *   channel-reachability control). Neither reaches the roster yet, so the
 *   derivation below is complete over the roster's fields — not over
 *   everything the manifest knows.
 *
 * THE GATE IS THE TYPE. `TOOL_LOCALS` is a `Record<ImplementedName,
 * ToolLocal>` where `ImplementedName` = every rostered name not explicitly
 * deferred in `NOT_YET_IMPLEMENTED`:
 *   - a rostered tool with no local entry   → TS2739 (missing property)
 *   - a local entry that is not rostered    → excess-property compile error
 * Either direction fails `tsgo`. This is what killed the historical drift:
 * this file used to hand-maintain the whole list and shipped deprecated
 * `syntropy_chat` while omitting live `syntropy_my_protocols`. It also means
 * a hand-typo in `mcpToolName`/`description` is impossible — those fields no
 * longer exist in this file to typo.
 *
 * Enum schemas (`MealTypeSchema`, etc.) are imported from `./generated/` —
 * auto-generated from `shared/schemas/enums.json`. The SJ MCP server
 * validates payloads server-side; parameter mismatches manifest as
 * user-visible 4xx responses, so keep enums as TypeBox literal unions.
 */

